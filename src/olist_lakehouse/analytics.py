"""Run the business questions in ``sql/analytics`` against the gold layer.

python -m olist_lakehouse.analytics            # print every report
python -m olist_lakehouse.analytics --export docs/sample_results.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

from olist_lakehouse.config import PROJECT_ROOT
from olist_lakehouse.gold import render
from olist_lakehouse.spark import TableStore, get_spark

ANALYTICS_DIR = PROJECT_ROOT / "sql" / "analytics"
GOLD_TABLES = (
    "dim_date",
    "dim_customer",
    "dim_product",
    "dim_seller",
    "fact_order_items",
    "fact_payments",
    "mart_daily_sales",
)


def run_reports(store: TableStore, limit: int = 20) -> dict[str, list[dict]]:
    if not store.settings.is_databricks:
        for t in GOLD_TABLES:
            store.read("gold", t)
    reports = {}
    for path in sorted(ANALYTICS_DIR.glob("*.sql")):
        df = store.spark.sql(render(path.read_text(), store))
        reports[path.stem] = [r.asDict() for r in df.limit(limit).collect()]
    return reports


def to_markdown(reports: dict[str, list[dict]]) -> str:
    note = (
        "Generated by `make analytics` on the synthetic sample (`make sample`), so the numbers "
        "are illustrative. Run on the real Kaggle data for real insights."
    )
    out = ["# Sample analytics results", "", note, ""]
    for name, rows in reports.items():
        out += [f"## {name}", ""]
        if not rows:
            out += ["_no rows_", ""]
            continue
        cols = list(rows[0])
        out.append("| " + " | ".join(cols) + " |")
        out.append("|" + "---|" * len(cols))
        out += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
        out.append("")
    return "\n".join(out)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--export", type=Path, help="write results to a markdown file")
    a = p.parse_args()
    reports = run_reports(TableStore(get_spark()))
    md = to_markdown(reports)
    if a.export:
        a.export.write_text(md)
        print(f"wrote {a.export}")
    else:
        print(md)


if __name__ == "__main__":
    main()
